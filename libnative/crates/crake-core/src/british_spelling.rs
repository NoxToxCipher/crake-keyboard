/// Converts an American English spelling to British English spelling if mapped.
pub fn to_british_spelling(word: &str) -> Option<&'static str> {
    AMERICAN_TO_BRITISH
        .binary_search_by(|(am, _)| am.cmp(&word))
        .ok()
        .map(|idx| AMERICAN_TO_BRITISH[idx].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_american_to_british_table_is_sorted() {
        for window in AMERICAN_TO_BRITISH.windows(2) {
            assert!(
                window[0].0 < window[1].0,
                "Table out of order: {} vs {}",
                window[0].0,
                window[1].0
            );
        }
    }

    #[test]
    fn test_british_spelling_lookups() {
        assert_eq!(to_british_spelling("color"), Some("colour"));
        assert_eq!(to_british_spelling("center"), Some("centre"));
        assert_eq!(to_british_spelling("analyze"), Some("analyse"));
        assert_eq!(to_british_spelling("defense"), Some("defence"));
        assert_eq!(to_british_spelling("realize"), Some("realise"));
        assert_eq!(to_british_spelling("traveled"), Some("travelled"));
        assert_eq!(to_british_spelling("keyboard"), None);
    }
}
